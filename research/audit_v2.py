"""Audit of the bench v2 runs: how each model worked, and whether the harness held up.

    python research/audit_v2.py results/bench_v2/*.jsonl > results/bench_v2/AUDIT.md

Reads every stored run (actions, replies, verdicts) and reports, per model:
harness health (turns the parser could not read, empty replies, actions read
back from native tool calls, runs with no answer or a crash), how the model
searched (first action, files it opened by kind, GREP terms, what it did with
RUN), and how quickly it reached the note describing the change. Nothing here
changes a result; it is the evidence behind them.
"""
from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from priorlock.bench import RIGHT_CALL  # noqa: E402

AGENTIC = ("repo_source", "repo_docs", "repo_docs_h1", "repo_docs_h2", "repo_docs_h3", "repo_run")


def kind(path: str, lib: str, info: set[str]) -> str:
    if path in info:
        return "the channel file"
    if path.startswith(f"docs/third_party/{lib}/"):
        return "library docs (other)"
    if path.startswith(f"{lib}/"):
        return "library folder"
    if path.startswith("data/"):
        return "input data"
    if path.startswith("tests/"):
        return "tests"
    if path.startswith("app/") or path.startswith("scripts/"):
        return "application code"
    if path.startswith("docs/"):
        return "project docs"
    return "project files (README, CHANGELOG, config)"


def pct(k: int, n: int) -> str:
    return f"{k / n:.0%} ({k}/{n})" if n else "–"


def main(files: list[str]) -> str:
    runs = [json.loads(line) for f in files for line in open(f)]
    tasks_dir = ROOT / "results" / "bench_v2" / "tasks_v2"
    meta = {}
    for t in {r["task"] for r in runs}:
        m = tasks_dir / t / ".priorlock" / "v2.json"
        if m.is_file():
            meta[t] = json.loads(m.read_text())
    by_model = collections.defaultdict(list)
    for r in runs:
        by_model[r["model"]].append(r)

    out = ["# Bench v2 audit", "",
           f"{len(runs)} runs from {len(by_model)} models. Generated by `research/audit_v2.py` "
           "from the stored runs; every number links back to a JSONL record.", "",
           "## Harness health", "",
           "| Model | Runs | Agent turns | Turns with no readable action | Empty replies | "
           "Actions read back from tool calls | Runs with no answer | Runs that crashed |",
           "|---|---|---|---|---|---|---|---|"]
    for m, rs in sorted(by_model.items()):
        ag = [r for r in rs if r["condition"] in AGENTIC]
        turns = sum(len(r.get("actions", [])) for r in ag)
        none = sum(1 for r in ag for a in r.get("actions", []) if a[0] == "NONE")
        empty = sum(1 for r in ag for x in r.get("replies", []) if not x.strip())
        rec = sum(r.get("recovered_calls", 0) for r in rs)
        noans = sum(1 for r in rs if set(r["verdicts"].values()) == {"no_answer"})
        crash = sum(1 for r in rs if "crashed" in r["verdicts"].values()
                    or "solution_crashed" in r.get("flags", []))
        out.append(f"| {m} | {len(rs)} | {turns} | {pct(none, turns)} | {empty} | {rec} | "
                   f"{noans} | {crash} |")

    out += ["", "## How each model searched (agentic runs, library compiled or readable)", ""]
    for m, rs in sorted(by_model.items()):
        ag = [r for r in rs if r["condition"] in AGENTIC]
        if not ag:
            continue
        first = collections.Counter((r.get("actions") or [["ANSWER", ""]])[0][0] for r in ag)
        answered_at_once = sum(1 for r in ag if r["turns"] == 1)
        opened = collections.Counter()
        for r in ag:
            mt = meta.get(r["task"], {})
            lib, info = mt.get("lib", ""), set(mt.get("info_files", []))
            for k in {kind(p, lib, info) for p in r.get("read", [])}:
                opened[k] += 1
        greps = collections.Counter(a[1].lower() for r in ag for a in r.get("actions", [])
                                    if a[0] == "GREP")
        runs_with_run = [r for r in ag if r.get("runs")]
        run_kinds = collections.Counter()
        for r in runs_with_run:
            for a in r.get("actions", []):
                if a[0] == "RUN":
                    code = a[1]
                    run_kinds["help() / __doc__ / inspect" if re.search(r"help\(|__doc__|inspect|dir\(", code)
                              else "called the library to test it" if "(" in code else "other"] += 1
        found_turn = []
        for r in ag:
            mt = meta.get(r["task"], {})
            info = set(mt.get("info_files", []))
            for i, a in enumerate(r.get("actions", []), 1):
                if a[0] == "READ" and a[1].strip("./") in info:
                    found_turn.append(i)
                    break
        out += [f"### {m}", "",
                f"- **Answered on the first turn, without any action:** {pct(answered_at_once, len(ag))} of agentic runs.",
                f"- **First action:** " + ", ".join(f"{k} {v}" for k, v in first.most_common()) + ".",
                f"- **Runs that opened each kind of file:** " + (", ".join(
                    f"{k} {pct(v, len(ag))}" for k, v in opened.most_common()) or "none") + ".",
                f"- **GREP searches:** {sum(greps.values())}" + (
                    "; most common: " + ", ".join(f"`{k}` ({v})" for k, v in greps.most_common(6))
                    if greps else "") + ".",
                f"- **RUN** (only in `repo_run`): used in {len(runs_with_run)} runs; "
                + (", ".join(f"{k} {v}" for k, v in run_kinds.most_common()) or "never") + ".",
                f"- **Reached the channel file by READ:** in {len(found_turn)} runs"
                + (f", at turn {sorted(found_turn)[len(found_turn) // 2]} (median)." if found_turn else "."),
                ""]

    out += ["## Do the verdicts follow from the code?", "",
            "A sample check: for runs scored as a right call, the code must name the probed "
            "function; for runs scored `bypassed`, it must not call it.", "",
            "| Model | Right-call probes whose code names the function | Bypassed probes whose code calls it |",
            "|---|---|---|"]
    from priorlock.repo_v2 import V2_BY_ID
    for m, rs in sorted(by_model.items()):
        ok = n = bad = nb = 0
        for r in rs:
            code = r.get("code") or ""
            for pid, v in r["verdicts"].items():
                fn = V2_BY_ID[pid].fn if pid in V2_BY_ID else None
                if not fn:
                    continue
                if v in RIGHT_CALL:
                    n += 1
                    ok += bool(re.search(rf"\b{re.escape(fn)}\b", code))
                if v == "bypassed":
                    nb += 1
                    bad += bool(re.search(rf"\.{re.escape(fn)}\(|\b{re.escape(fn)}\(", code))
        out.append(f"| {m} | {pct(ok, n)} | {pct(bad, nb)} |")
    out += ["", "After the regrade, a bypassed probe whose code still mentions the function is one "
            "the code never reached without crashing (a branch not taken, a helper never called). "
            "Listed for manual review:", ""]
    shown = 0
    for r in runs:
        code = r.get("code") or ""
        for pid, v in r["verdicts"].items():
            fn = V2_BY_ID[pid].fn if pid in V2_BY_ID else None
            if v == "bypassed" and fn and re.search(rf"\b{re.escape(fn)}\(", code) and shown < 8:
                out.append(f"- {r['model']} · {r['task']} · {r['condition']} · `{fn}`")
                shown += 1
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(main(sys.argv[1:]))
